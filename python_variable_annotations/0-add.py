#!/usr/bin/python3
"""Task 0: Add two floats with annotations."""


def add(a: float, b: float) -> float:
    """Returns the sum of a and b as a float.

    Args:
        a (float): The first float to add.
        b (float): The second float to add.

    Returns:
        float: The sum of a and b.
    """
    return a + b
